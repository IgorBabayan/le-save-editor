using LE.SaveEditor.Presentation.Services;
using LE.SaveEditor.Presentation.Services.Toasts;
using LE.SaveEditor.Presentation.ViewModels.Database;
using LE.SaveEditor.Presentation.ViewModels.Notifications;
using LE.SaveEditor.Presentation.ViewModels.Settings;
using LE.SaveEditor.Presentation.ViewModels.Shell;
using LE.SaveEditor.Presentation.Views;
using LE.SaveEditor.Presentation.Views.Database;
using LE.SaveEditor.Presentation.Views.Settings;
using LE.SaveEditor.Services.GameData;
using LE.SaveEditor.Services.GameData.Items;
using LE.SaveEditor.Services.Notifications;
using LE.SaveEditor.Services.Saves;
using LE.SaveEditor.Services.Settings;
using LE.SaveEditor.Services.Theming;
using LE.SaveEditor.Services.Updates;

namespace LE.SaveEditor.Extensions;

static class ServiceCollectionExtensions
{
    extension(IServiceCollection services)
    {
        public IServiceCollection AddApplicationServices() => services
            .AddInfrastructure()
            .AddPresentation();

        private IServiceCollection AddInfrastructure()
        {
            services.AddSingleton<ISettingsService, JsonSettingsService>();
            services.AddSingleton<IThemeService, ThemeService>();
            services.AddSingleton<IUpdateService, GitHubUpdateService>();
            services.AddSingleton<INotificationService, JsonNotificationService>();

            // Save files
            services.AddSingleton<ISaveFolderScanner, SaveFolderScanner>();
            services.AddSingleton<ICharacterSaveParser, CharacterSaveParser>();
            services.AddSingleton<ISaveFolderLoader, SaveFolderLoader>();
            services.AddSingleton<ICharacterSaveWriter, CharacterSaveWriter>();

            // Game data generated by LE.SaveEditor.DB (%APPDATA%\LE.SaveEditor\base.db, \Icons)
            services.AddSingleton<IIconProvider, IconProvider>();
            services.AddSingleton<ICharacterIconProvider, CharacterIconProvider>();
            services.AddSingleton<IDatabaseGenerator, DatabaseGenerator>();
            services.AddSingleton<IItemBaseCatalog, ItemBaseCatalog>();

            return services;
        }

        private IServiceCollection AddPresentation()
        {
            // Services
            services.AddSingleton<IDialogService, DialogService>();
            services.AddSingleton<IFolderPickerService, FolderPickerService>();
            services.AddSingleton<IToastService, ToastService>();
            services.AddSingleton<IAutoUpdater, AutoUpdater>();

            // Notification center (bell in the title bar)
            services.AddSingleton<NotificationCenterViewModel>();

            // Shell
            services.AddSingleton<MainViewModel>();
            services.AddSingleton<MainWindow>();

            // Settings (new instance every time the dialog opens)
            services.AddTransient<SettingsViewModel>();
            services.AddTransient<SettingsWindow>();

            // Database generator (new instance every time the dialog opens)
            services.AddTransient<DatabaseGeneratorViewModel>();
            services.AddTransient<DatabaseGeneratorWindow>();

            return services;
        }
    }
}
